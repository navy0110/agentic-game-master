"""Build a single-file Hosted Agent from the tested local engine's pure logic."""
import ast
from pathlib import Path
import textwrap

root = Path(__file__).resolve().parents[1]
source = (root / 'agm/engine.py').read_text(encoding='utf-8')
tree = ast.parse(source)
pieces = []
for node in tree.body:
    if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id in {'SYSTEM', 'RESPONSE_FORMAT'} for t in node.targets):
        pieces.append(ast.get_source_segment(source, node))
    elif isinstance(node, ast.FunctionDef) and node.name in {'generation_options', 'completion_text', 'parse_result', 'normalize_message', 'render_status', 'render_player_status'}:
        pieces.append(ast.get_source_segment(source, node))
start = source.index('            if previous is None:', source.index('    def _turn('))
end = source.index('            # Hold SQLite', start)
body = textwrap.dedent(source[start:end]).replace('self.provider(', 'provider(')
advance = 'def advance_state(previous, request, provider):\n' + textwrap.indent(body, '    ') + '    return result\n'
header = '# Generated by hosted/build.py. No secrets. Paste into Agentverse Build.\nimport json\nimport hashlib\n'
runtime = (root / 'hosted/runtime.py.txt').read_text(encoding='utf-8')
(root / 'hosted/agent.py').write_text(header + '\n\n'.join(pieces) + '\n\n' + advance + '\n\n' + runtime, encoding='utf-8')
print('Built hosted/agent.py')
